def environment_list(name):
    return [
        value.strip()
        for value in os.environ.get(name, '').split(',')
        if value.strip()
    ]


ALLOWED_HOSTS = environment_list('DJANGO_ALLOWED_HOSTS')
render_hostname = os.environ.get('RENDER_EXTERNAL_HOSTNAME')
if render_hostname and render_hostname not in ALLOWED_HOSTS:
    ALLOWED_HOSTS.append(render_hostname)
if DEBUG:
    for host in ('localhost', '127.0.0.1', '[::1]', 'testserver'):
        if host not in ALLOWED_HOSTS:
            ALLOWED_HOSTS.append(host)
elif not ALLOWED_HOSTS:
    raise ImproperlyConfigured(
        'Set DJANGO_ALLOWED_HOSTS or use a Render web service hostname.'
    )

CSRF_TRUSTED_ORIGINS = environment_list('DJANGO_CSRF_TRUSTED_ORIGINS')
if render_hostname:
    render_origin = f'https://{render_hostname}'
    if render_origin not in CSRF_TRUSTED_ORIGINS:
        CSRF_TRUSTED_ORIGINS.append(render_origin)


